const KEY = "folix_lang";
export const getLang = () => localStorage.getItem(KEY) || "ar";

/** Apply a language: text, direction, title/description, persist. */
export function setLang(lang) {
  localStorage.setItem(KEY, lang);
  const d = T[lang];
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
  document.title = d.meta_title;
  document.querySelector('meta[name="description"]')?.setAttribute("content", d.meta_desc);
  document.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = d[el.dataset.i18n] ?? el.textContent; });
  const btn = document.getElementById("lang");
  document.querySelectorAll("[data-i18n-ph]").forEach(el => { el.placeholder = d[el.dataset.i18nPh] ?? ""; });
  if (btn) btn.textContent = lang === "ar" ? "EN" : "عربي";
  dispatchEvent(new Event("langchange")); // dynamic (Supabase-rendered) parts re-render on this
}
export const t = k => T[getLang()][k] ?? k;
